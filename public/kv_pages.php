            $body .= '<h3 id="q' . $n . '">Q.' . kv_e($q) . '</h3>'
                   . '<p><b>A.' . kv_e($a) . '</b></p>' . $detail;
        }
        $toc .= '</ul>';
    }
    return $h . $toc . '<hr>' . $body;
}

