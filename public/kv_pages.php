    }

    if ($_SERVER['REQUEST_METHOD'] === 'POST') {
        foreach (array_keys($in) as $k) { $in[$k] = trim((string)($_POST[$k] ?? '')); }
        if (!kv_csrf_ok()) {
            $err = '時間が経ちすぎたようです。お手数ですがもう一度送信してください。';
        } elseif ($in['name'] === '' || $in['email'] === '' || $in['body'] === '') {
            $err = 'お名前・メールアドレス・お問い合わせ内容をご記入ください。';
        } elseif (!filter_var($in['email'], FILTER_VALIDATE_EMAIL)) {
            $err = 'メールアドレスの形をご確認ください。';
        } else {
            // ヘッダに改行を混ぜられないよう、差出人は店のアドレス固定・返信先だけお客様に向ける
            $reply = str_replace(["\r", "\n"], '', $in['email']);
            $body = "お名前: {$in['name']}\nメール: {$in['email']}\n電話: {$in['tel']}\n"
                  . "受信日時: " . date('Y-m-d H:i:s') . "\n"
                  . "------------------------------------\n" . $in['body'] . "\n";
            $h = 'From: ' . mb_encode_mimeheader(kv_shop('name')) . ' <' . $to . '>' . "\r\n"
               . 'Reply-To: ' . $reply . "\r\n"
               . 'Content-Type: text/plain; charset=UTF-8' . "\r\n";
            $sent = @mail($to, mb_encode_mimeheader('【お問い合わせ】' . $in['name'] . ' 様'), $body, $h);
            if (!$sent) {
                $err = '送信できませんでした。お手数ですが ' . $to . ' 宛にメールでご連絡ください。';
            }
        }
    }

    kv_head('お問い合わせ', '在庫・納期・お見積り・掲載外商品のお取り寄せはこちらから。', '/contact');
    echo '<div class="wrap"><nav class="crumb"><a href="' . kv_url('') . '">トップ</a> › '
       . 'お問い合わせ</nav><h1>お問い合わせ</h1>';

    if ($sent) {
        echo '<div class="panel"><p>お問い合わせを受け付けました。ありがとうございます。</p>'
           . '<p>内容を確認のうえ、ご記入いただいたメールアドレスへご返信します。'
           . 'メーカー・仕入先への確認が必要な場合、お返事までに数日いただくことがあります。</p>'
           . '<p><a class="btn" href="' . kv_url('') . '">トップへ</a></p></div>';
        kv_footer();
        return;
    }

    echo '<div class="panel desc">'
       . '<p>在庫確認、納期確認、お見積り、掲載されていない商品のお取り寄せなどは'
       . 'お気軽にどうぞ。</p>'
       . '<p class="note">※間違いをなくすため、お問い合わせはお電話ではお受けしておりません。'
       . '在庫確認、納期確認、お見積りなどは口頭でのご回答はできません。</p>'
       . '<h2>ご記入いただきたいこと</h2><ul>'
       . '<li>商品型式・商品名・メーカー（お見積り・お取り寄せのとき）</li>'
       . '<li>受注番号・ご注文日時・お名前（ご注文後のお問い合わせのとき）</li>'
       . '<li>どのように使用して故障したか、どこがどう故障したか（故障のとき）</li></ul>'
       . '<p class="note">※弊社に商品の技術的な知識はございませんので、'
       . 'そのようなご質問にはお答えできません。直接メーカーにお問い合わせいただくか、'
       . '商品カタログなどをご確認ください。</p></div>';

    if ($err !== '') { echo '<div class="alert">' . kv_e($err) . '</div>'; }

    echo '<form method="post" class="panel">'
       . '<input type="hidden" name="csrf" value="' . kv_e(kv_csrf()) . '">'
       . '<table class="formtbl">'
       . '<tr><th>お名前<span class="req">必須</span></th>'
       . '<td><input type="text" name="name" value="' . kv_e($in['name']) . '" required></td></tr>'
       . '<tr><th>メールアドレス<span class="req">必須</span></th>'
       . '<td><input type="email" name="email" value="' . kv_e($in['email']) . '" required>'
       . '<div class="hint">このアドレスへご返信します。'
       . '携帯電話のアドレスはPCからのメールを拒否している場合があります。</div></td></tr>'
       . '<tr><th>電話番号</th>'
       . '<td><input type="text" name="tel" value="' . kv_e($in['tel']) . '">'
       . '<div class="hint">こちらからお電話することはありません。</div></td></tr>'
       . '<tr><th>お問い合わせ内容<span class="req">必須</span></th>'
       . '<td><textarea name="body" rows="10" required>' . kv_e($in['body']) . '</textarea></td></tr>'
       . '</table>'
       . '<p class="note">送信をもって、'
       . '<a href="' . kv_url('privacy') . '" target="_blank" rel="noopener">プライバシーポリシー</a>'
       . 'に同意いただいたものとします。</p>'
       . '<p><button class="btn" type="submit">送信する</button></p></form>';

    echo '<div class="panel desc"><h2>メール・FAXで送る場合</h2><table>'
       . '<tr><th>メール</th><td><a href="mailto:' . kv_e($to) . '">' . kv_e($to) . '</a></td></tr>'
       . '<tr><th>FAX</th><td>' . kv_e(kv_shop('fax')) . '</td></tr>'
       . '</table></div></div>';
    kv_footer();
}

/** ご利用案内の1節。見出し帯 → 中身 → 区切り帯（現行サイトと同じ組み立て）。 */
function kv_help_section(string $title, string $body): string
{
    return '<div class="helpsec"><div class="sechead">' . kv_e($title) . '</div>'
        . '<div class="secbody">' . $body . '</div>'
        . '<div class="secfoot"></div></div>';
}

/**
 * 商品番号の先頭に付く社内記号の一覧。
 * **決め打ちで書かない。** 現行サイトの記述をそのまま写したら、この店で
 * 1件も使っていない記号（HSH- KNM- MMS- NKK-）を載せ、実際に使っている
 * 記号（DRY- ZAO- INE- MRI- FKS-）が抜けていた（2026-09-14）。
 * 3文字＋ハイフンの形で、実際に商品がある物だけを多い順に出す。
 */
function kv_code_prefixes(int $min = 20): string
{
    $rows = kv_db()->query(
        'SELECT substr(model_number,1,3) AS p, COUNT(*) AS c FROM products
          WHERE hidden=0 AND substr(model_number,4,1)="-"
            AND substr(model_number,1,3) GLOB "[A-Z][A-Z][A-Z]"
          GROUP BY p HAVING c >= ' . $min . ' ORDER BY c DESC'
    )->fetchAll(PDO::FETCH_ASSOC);
    if (!$rows) { return ''; }
    $list = array_map(static fn($r) => $r['p'] . '-', $rows);
    return '「' . kv_e(implode(', ', $list)) . '」';
}
