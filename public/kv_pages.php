/** 絶対URL。メール本文に入れるので、パスだけでは足りない。 */
function kv_site_url(string $path = ''): string
{
    $https = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off')
        || (($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https');
    $host = (string)($_SERVER['HTTP_HOST'] ?? '');
    return $host === '' ? kv_url($path) : ($https ? 'https://' : 'http://') . $host . kv_url($path);
}

