/** 代引きを受けるか。現行 exdirect.net の「お支払い方法」は銀行振込とカードのみ。 */
function kv_cod_enabled(): bool { return (bool)(kv_cfg()['shop']['cod'] ?? false); }
/** PayPal を受けるか。同上。 */
function kv_paypal_enabled(): bool { return (bool)(kv_cfg()['shop']['paypal'] ?? false); }

/** 受けられる支払い方法を日本語で並べる。 */
function kv_pay_methods(): string
{
    $m = ['銀行振込'];
    if (kv_stripe_ready()) { $m[] = 'クレジットカード'; }
    if (kv_paypal_enabled()) { $m[] = 'PayPal'; }
    if (kv_cod_enabled()) { $m[] = '代金引換'; }
    return implode('、', $m);
}

