              ['ご注文についてのご質問', $qa_order]] as [$sec, $qa]) {
        $toc .= '<h2>' . kv_e($sec) . '</h2><ul>';
        $body .= '<h2>' . kv_e($sec) . '</h2>';
        foreach ($qa as [$q, $a, $detail]) {
            $n++;
